#!/usr/bin/env bash
# SPDX-FileCopyrightText: 2026 RavenOS
# SPDX-License-Identifier: Apache-2.0
#
# Builds the RavenOS fork of Dicio (the "Hey Raven" voice assistant) and drops it into this
# folder as a prebuilt: Dicio.apk plus an Android.mk that installs it as a privileged app.
#   bash vendor/ravenos/apps/Dicio/build-dicio.sh
#   bash vendor/ravenos/apps/Dicio/build-dicio.sh --export   # also refresh patches/ from the fork
#
# The fork is upstream Dicio at $UPSTREAM_COMMIT plus patches/*.patch. If $DICIO_SRC doesn't
# exist it is recreated from those. Before building, the script checks that the fork carries
# exactly the patches in this folder, so a stale fork can't overwrite Dicio.apk; commit new
# work in the fork and use --export, or rebuild the fork from the patches.
# DICIO_SRC and DICIO_GRADLE_HOME override where the fork and Gradle's cache live. Building runs in Docker (build/Dockerfile), which accepts
# the Android SDK License Agreement.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DICIO_SRC="${DICIO_SRC:-/mnt/media/ravenos/dicio-src}"
GRADLE_HOME="${DICIO_GRADLE_HOME:-/mnt/media/ravenos/dicio-gradle}"
UPSTREAM=https://github.com/Stypox/dicio-android
UPSTREAM_COMMIT=3d1c15434f1cae94670dead51cfb127bb4f16705
IMAGE=ravenos-dicio-build
ABI=armeabi-v7a  # the Echo Show 8 runs a 32-bit ARM userspace

if [ ! -d "$DICIO_SRC/.git" ]; then
    echo "=== recreating the fork in $DICIO_SRC"
    git clone "$UPSTREAM" "$DICIO_SRC"
    git -C "$DICIO_SRC" checkout -b ravenos "$UPSTREAM_COMMIT"
    git -C "$DICIO_SRC" am "$HERE"/patches/*.patch
fi

# One patch-id per patch, in order: the change itself, whatever the commit metadata.
repo_ids() {
    local p
    for p in "$HERE"/patches/*.patch; do
        git -C "$DICIO_SRC" patch-id --stable < "$p" | cut -d' ' -f1
    done
}
fork_ids() {
    git -C "$DICIO_SRC" format-patch --stdout "$UPSTREAM_COMMIT"..HEAD \
        | git -C "$DICIO_SRC" patch-id --stable | cut -d' ' -f1
}

if [ "${1:-}" = "--export" ]; then
    # Refuse to drop a patch the fork doesn't carry (e.g. one pulled into this repo since).
    missing=$(comm -23 <(repo_ids | sort) <(fork_ids | sort))
    if [ -n "$missing" ]; then
        echo "The fork in $DICIO_SRC lacks patches that are in $HERE/patches; apply them first." >&2
        exit 1
    fi
    tmp=$(mktemp -d)
    git -C "$DICIO_SRC" format-patch -q "$UPSTREAM_COMMIT" -o "$tmp"
    rm -f "$HERE"/patches/*.patch
    mkdir -p "$HERE/patches"
    mv "$tmp"/*.patch "$HERE/patches/"
    rmdir "$tmp"
    echo "=== exported $(ls "$HERE"/patches | wc -l) patches"
elif [ "$(repo_ids)" != "$(fork_ids)" ]; then
    echo "The fork in $DICIO_SRC doesn't match $HERE/patches." >&2
    echo "Export the fork's commits with --export, or move the fork away to recreate it." >&2
    exit 1
fi

echo "=== building"
docker build -q -t "$IMAGE" "$HERE/build" >/dev/null
mkdir -p "$GRADLE_HOME"
docker run --rm --cpus="${DICIO_CPUS:-6}" -v "$DICIO_SRC:/src" -v "$GRADLE_HOME:/root/.gradle" \
    "$IMAGE" nice -n 15 ./gradlew --no-daemon assembleRelease

cp "$DICIO_SRC/app/build/outputs/apk/release/app-release-unsigned.apk" "$HERE/Dicio.apk"

# System apps can't unpack native libraries at runtime, so the build installs the 32-bit ARM
# ones next to the APK.
jni_libs=$(unzip -Z1 "$HERE/Dicio.apk" "lib/$ABI/*.so" | sed 's/^/    @/' | sed '$!s/$/ \\/')
cat > "$HERE/Android.mk" <<EOF
# SPDX-FileCopyrightText: 2026 RavenOS
# SPDX-License-Identifier: Apache-2.0
#
# Generated by build-dicio.sh: Dicio, the "Hey Raven" voice assistant, as a privileged app.
LOCAL_PATH := \$(call my-dir)

include \$(CLEAR_VARS)
LOCAL_MODULE := Dicio
LOCAL_MODULE_CLASS := APPS
LOCAL_MODULE_TAGS := optional
LOCAL_MODULE_SUFFIX := \$(COMMON_ANDROID_PACKAGE_SUFFIX)
LOCAL_SRC_FILES := Dicio.apk
# The build signs the unsigned APK; it needs no platform signature, only priv-app status.
LOCAL_CERTIFICATE := testkey
LOCAL_PRIVILEGED_MODULE := true
LOCAL_MULTILIB := 32
LOCAL_DEX_PREOPT := false
LOCAL_PREBUILT_JNI_LIBS := \\
$jni_libs
LOCAL_REQUIRED_MODULES := \\
    privapp-permissions-org.stypox.dicio.xml \\
    default-permissions-org.stypox.dicio.xml
include \$(BUILD_PREBUILT)

include \$(CLEAR_VARS)
LOCAL_MODULE := privapp-permissions-org.stypox.dicio.xml
LOCAL_MODULE_CLASS := ETC
LOCAL_MODULE_TAGS := optional
LOCAL_MODULE_PATH := \$(TARGET_OUT_ETC)/permissions
LOCAL_SRC_FILES := etc/privapp-permissions-org.stypox.dicio.xml
include \$(BUILD_PREBUILT)

include \$(CLEAR_VARS)
LOCAL_MODULE := default-permissions-org.stypox.dicio.xml
LOCAL_MODULE_CLASS := ETC
LOCAL_MODULE_TAGS := optional
LOCAL_MODULE_PATH := \$(TARGET_OUT_ETC)/default-permissions
LOCAL_SRC_FILES := etc/default-permissions-org.stypox.dicio.xml
include \$(BUILD_PREBUILT)
EOF
echo "=== done: $HERE/Dicio.apk ($(du -h "$HERE/Dicio.apk" | cut -f1)), $(echo "$jni_libs" | wc -l) native libraries"
