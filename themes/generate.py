# Apps whose backdrop follows touches, with the prefix their colors use. An app joins once its
# own res/values defines <prefix>_touch_glow: framework-res and RavenHome build without
# --auto-add-overlay, so an overlay can't add a color the app lacks.
TOUCH_GLOW_APPS = [
    (SETTINGS_RES, "raven"),
    (SEARCH_RES, "raven"),
    (LATINIME_RES, "raven"),
    (RAVENHOME_RES, "settings"),
    (ECHOPARTS_RES, "settings"),
    (LINEAGEPARTS_RES, "raven"),
    (PERMISSION_RES, "raven"),
    (DOCUMENTSUI_RES, "raven"),
]


def touch_glow_xml(p, prefix):
    return render(p["name"], [("color", prefix + "_touch_glow", TOUCH_GLOW[p["name"]])])


def render(name, rows):
    body = "".join('    <%s name="%s">%s</%s>\n' % (t, n, v, t) for t, n, v in rows)
    return HEADER.format(name=name) + body + "</resources>\n"


def outputs():
    for variant, qualifiers in VARIANTS.items():
        for qualifier, palette in qualifiers.items():
            base = os.path.join(HERE, variant)
            yield (os.path.join(base, SETTINGS_RES, qualifier, "raven_glass.xml"),
                   settings_xml(palette))
            yield (os.path.join(base, SEARCH_RES, qualifier, "raven_glass.xml"),
                   settings_xml(palette))
            yield (os.path.join(base, LATINIME_RES, qualifier, "raven_glass.xml"),
                   latinime_xml(palette))
            # The framework: toasts, dialogs and popup menus in every app.
            yield (os.path.join(base, FRAMEWORK_RES, qualifier, "raven_glass.xml"),
                   settings_xml(palette))
            # Files (DocumentsUI) too.
            yield (os.path.join(base, DOCUMENTSUI_RES, qualifier, "raven_glass.xml"),
                   settings_xml(palette))
            # Default apps and Permission manager (PermissionController) as well.
            yield (os.path.join(base, PERMISSION_RES, qualifier, "raven_glass.xml"),
                   settings_xml(palette))
            # Quick Settings and the screen record dialog use Settings' raven_* names too.
            yield (os.path.join(base, SYSTEMUI_RES, qualifier, "raven_glass.xml"),
                   settings_xml(palette))
            # LineageParts (Charging sounds, Status bar, ...) uses Settings' raven_* names.
            yield (os.path.join(base, LINEAGEPARTS_RES, qualifier, "raven_glass.xml"),
                   settings_xml(palette))
            yield (os.path.join(base, RAVENHOME_RES, qualifier, "settings_glass.xml"),
                   ravenhome_xml(palette))
            # EchoParts (Microphone processing and friends) uses the same settings_* names.
            yield (os.path.join(base, ECHOPARTS_RES, qualifier, "settings_glass.xml"),
                   ravenhome_xml(palette))
            for res, prefix in TOUCH_GLOW_APPS:
                yield (os.path.join(base, res, qualifier, "touch_glow.xml"),
                       touch_glow_xml(palette, prefix))
    yield (os.path.normpath(RAVENHOME_DEFAULTS),
           ravenhome_xml(VARIANTS[DEFAULT_VARIANT]["values"]))
    yield (os.path.normpath(ECHOPARTS_DEFAULTS),
           ravenhome_xml(VARIANTS[DEFAULT_VARIANT]["values"]))


def main():
    parser = argparse.ArgumentParser(
        description="Writes the RavenOS glass theme overlays, one folder per variant.")
    parser.add_argument("--check", action="store_true",
                        help="report variants that differ from this script instead of writing")
    args = parser.parse_args()
    stale = []
    for path, text in outputs():
        current = open(path).read() if os.path.exists(path) else None
        if current == text:
            continue
        if args.check:
            stale.append(os.path.relpath(path, HERE))
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(text)
        print("wrote", os.path.relpath(path, HERE))
    if stale:
        print("out of date:\n  " + "\n  ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
