def ravenhome_xml(p):
    # RavenHome has its own raven_* palette for the home screen, so the RavenOS settings
    # page uses settings_* names.
    p = full(p)
    g = p["glows"]
    rows = [
        ("color", "settings_bg", p["bg"]),
        ("color", "settings_glow_1", g[0]),
        ("color", "settings_glow_2", g[1]),
        ("color", "settings_glow_3", g[2]),
        ("color", "settings_fg", p["fg"]),
        ("color", "settings_fg_2", p["fg2"]),
        ("color", "settings_fg_3", p["fg3"]),
        ("color", "settings_card", p["glass"]),
        ("color", "settings_card_stroke", p["stroke"]),
        ("color", "settings_separator", p["sep"]),
        ("color", "settings_ripple", p["ripple"]),
        ("color", "settings_accent", p["accent"]),
        ("color", "settings_surface", p["surface"]),
        ("color", "settings_on_accent", p["on_accent"]),
        # Home screen buttons sit on a photo or video, so they are the surface color at
        # 72% instead of the faint card glass.
        ("color", "settings_home_glass", "#B8" + p["surface"][3:]),
        ("dimen", "settings_card_radius", "%ddp" % p["card_radius"]),
    ]
    return render(p["name"], rows)


