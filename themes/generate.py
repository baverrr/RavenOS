def full(p):
    return {**DARK_DEFAULTS, **p}


def settings_xml(p):
    p = full(p)
    g = p["glows"]
    rows = [
        ("color", "raven_bg", p["bg"]),
        ("color", "raven_glow_1", g[0]),
        ("color", "raven_glow_2", g[1]),
        ("color", "raven_glow_3", g[2]),
        ("color", "raven_fg", p["fg"]),
        ("color", "raven_fg_2", p["fg2"]),
        ("color", "raven_fg_3", p["fg3"]),
        ("color", "raven_glass", p["glass"]),
        ("color", "raven_glass_stroke", p["stroke"]),
        ("color", "raven_separator", p["sep"]),
        ("color", "raven_ripple", p["ripple"]),
        ("color", "raven_accent", p["accent"]),
        ("color", "raven_on_accent", p["on_accent"]),
        ("color", "raven_switchbar_on", p["on_glass"]),
        ("color", "raven_switchbar_on_stroke", p["on_stroke"]),
        ("color", "raven_tab_selected", p["tab_selected"]),
        ("color", "raven_surface", p["surface"]),
        ("bool", "raven_light_ui", "true" if p["light"] else "false"),
        ("dimen", "raven_card_radius", "%ddp" % p["card_radius"]),
    ]
    return render(p["name"], rows)


